package gen

import (
	"io"

	"github.com/123456890987654321/yaggo/internal/spec"
)

// GenerateBodyTypes writes inline request body structs (for operations whose
// requestBody schema is not a $ref to a named component).
func GenerateBodyTypes(w io.Writer, api *spec.OpenAPI, pkg string) error {
	if err := validateSpecIdentifiers(api); err != nil {
		return err
	}
	if err := validateSpecPatterns(api); err != nil {
		return err
	}
	p := &printer{w: w}
	ops := collectOps(api)

	imports := newImportSet()
	var bodies []struct {
		typeName string
		schema   *spec.Schema
	}
	for _, mo := range ops {
		_, bs := requestBodyContent(mo.Op)
		if bs == nil || bs.Ref != "" {
			continue
		}
		name := operationName(mo.Method, mo.Path, mo.Op)
		typeName := name + "Body"
		bodies = append(bodies, struct {
			typeName string
			schema   *spec.Schema
		}{typeName, bs})
		eff := effectiveSchema(bs, api)
		if hasValidation(eff, api) {
			imports.add("fmt")
		}
		collectValidationImports(eff, imports)
	}
	if len(bodies) == 0 {
		return nil
	}

	p.line("// Code generated by yaggo. DO NOT EDIT.")
	p.line("")
	p.linef("package %s", pkg)
	p.line("")
	imports.writeBlock(p)

	for _, b := range bodies {
		// Non-object inline bodies (a top-level array, scalar, etc.)
		// don't fit the struct mold — emitting `type DoItBody struct {}`
		// would leave the JSON decoder unable to read the actual payload.
		// Emit a Go alias to the underlying type instead, so JSON unmarshal
		// targets the right shape.
		eff := effectiveSchema(b.schema, api)
		isStructLike := eff.Type.Primary() == "object" || len(eff.Properties) > 0 || len(eff.AllOf) > 0
		if !isStructLike && !eff.Type.IsEmpty() {
			p.linef("type %s = %s", b.typeName, schemaToGoType(eff, false))
			p.line("")
			continue
		}
		writeStruct(p, b.typeName, b.schema, api)
	}

	// Emit any compiled regex vars used by body-type validations.
	emitBodyPatternVars(p, ops, api)

	return p.err
}

func emitBodyPatternVars(p *printer, ops []MethodOp, api *spec.OpenAPI) {
	type entry struct {
		varName string
		pattern string
	}
	var entries []entry
	for _, mo := range ops {
		_, bs := requestBodyContent(mo.Op)
		if bs == nil || bs.Ref != "" {
			continue
		}
		typeName := operationName(mo.Method, mo.Path, mo.Op) + "Body"
		eff := effectiveSchema(bs, api)
		for _, fieldName := range sortedKeys(eff.Properties) {
			f := eff.Properties[fieldName]
			if f == nil {
				continue
			}
			if f.Pattern != "" && f.Type.Primary() == "string" {
				entries = append(entries, entry{
					varName: patternVarName(typeName, toGoFieldName(fieldName)),
					pattern: f.Pattern,
				})
			}
			if f.Type.Primary() == "array" && f.Items != nil && f.Items.Pattern != "" && f.Items.Type.Primary() == "string" {
				entries = append(entries, entry{
					varName: itemPatternVarName(typeName, toGoFieldName(fieldName)),
					pattern: f.Items.Pattern,
				})
			}
		}
	}
	if len(entries) == 0 {
		return
	}
	p.line("var (")
	for _, e := range entries {
		p.linef("\t%s = regexp.MustCompile(%q)", e.varName, e.pattern)
	}
	p.line(")")
	p.line("")
}
