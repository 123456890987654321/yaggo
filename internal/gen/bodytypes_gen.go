package gen

import (
	"io"

	"github.com/123456890987654321/yago/internal/spec"
)

// GenerateBodyTypes writes inline request body structs (for operations whose
// requestBody schema is not a $ref to a named component).
func GenerateBodyTypes(w io.Writer, api *spec.OpenAPI, pkg string) error {
	p := &printer{w: w}
	ops := collectOps(api)

	var needsTypes bool
	for _, mo := range ops {
		bs := requestBodySchema(mo.Op)
		if bs != nil && bs.Ref == "" {
			needsTypes = true
			break
		}
	}
	if !needsTypes {
		return nil
	}

	p.line("// Code generated by yago. DO NOT EDIT.")
	p.line("")
	p.linef("package %s", pkg)
	p.line("")
	p.line(`import "fmt"`)
	p.line("")

	for _, mo := range ops {
		bs := requestBodySchema(mo.Op)
		if bs == nil || bs.Ref != "" {
			continue
		}
		name := operationName(mo.Method, mo.Path, mo.Op)
		typeName := name + "Body"
		writeStruct(p, typeName, bs, api)
	}

	p.line("var _ = fmt.Sprintf")

	return p.err
}
