// GenerateTypes writes the types/models Go file.
func GenerateTypes(w io.Writer, api *spec.OpenAPI, pkg string) error {
	// Security: pre-flight identifier and vendor-extension validation. Catching
	// malicious or malformed spec values here means the generator never has a
	// chance to interpolate them into Go source — even into the unformatted
	// "for debugging" file written when go/format later fails. This is the
	// trust boundary for "third-party spec → CI auto-generates" pipelines.
	if err := validateSpecIdentifiers(api); err != nil {
		return err
	}
	if err := validateSpecPatterns(api); err != nil {
		return err
	}

	p := &printer{w: w}
	p.line("// Code generated by yaggo. DO NOT EDIT.")
	p.line("")
	p.linef("package %s", pkg)
	p.line("")

	imports := newImportSet()

	// Imports must appear before any type declarations, so we walk schemas
	// once to compute the import set, then again below to write types.
	// The conditions here must stay in sync with what writeSchemaType /
	// writeStructValidate actually emit; missing an import yields code that
	// fails go/format with "undefined: fmt", which is loud but unpleasant.
	for _, name := range sortedKeys(api.Components.Schemas) {
		s := api.Components.Schemas[name]
		effective := effectiveSchema(s, api)
		if s.XGoType != "" {
			if s.XGoImport != "" {
				imports.add(s.XGoImport)
			}
			continue
		}
		// Enum schemas emit fmt.Errorf in their Validate(). The check covers
		// string / integer / number / boolean enums — enumScalarKind returns
		// "" for shapes we don't currently codegen for, in which case no
		// Validate is emitted at all.
		if len(effective.Enum) > 0 && enumScalarKind(effective) != "" {
			imports.add("fmt")
			// Numeric enum entries can be NaN/±Inf (.nan/.inf in YAML).
			// enumLiteral routes those through formatBound → math.NaN()
			// / math.Inf(±1), so we need the math import alongside fmt.
			switch enumScalarKind(effective) {
			case "float32", "float64":
				for _, v := range effective.Enum {
					if n, ok := v.(float64); ok && boundNeedsMath(n) {
						imports.add("math")
						break
					}
				}
			}
		}
		if hasValidation(effective, api) {
			imports.add("fmt")
		}
		// Primitive aliases with keyword constraints get their own Validate
		// on the named type; collect the imports its body uses (utf8 for
		// rune length, regexp for pattern, math for ±Inf/NaN bounds).
		if hasPrimitiveConstraints(effective) {
			collectPrimitiveValidateImports(effective, imports)
		}
		collectValidationImports(effective, imports)
	}

	imports.writeBlock(p)

	for _, name := range sortedKeys(api.Components.Schemas) {
		s := api.Components.Schemas[name]
		if err := writeSchemaType(p, name, s, api); err != nil {
			return fmt.Errorf("schema %q: %w", name, err)
		}
	}

	emitPatternVars(p, api)

	return p.err
}

func writeSchemaType(p *printer, name string, s *spec.Schema, api *spec.OpenAPI) error {
	goName := toGoName(name)

	// Description (when present) precedes every emitted shape — alias, enum,
	// struct, primitive — so godoc tools pick it up. emitDoc handles the
	// single-line sanitisation and prefix.
	emitDoc := func() {
		if s.Description != "" {
			p.linef("// %s %s", goName, sanitizeComment(s.Description))
		}
	}

	// x-go-type override: emit a plain alias and skip any other generation.
	if s.XGoType != "" {
		emitDoc()
		p.linef("type %s = %s", goName, s.XGoType)
		p.line("")
		return p.err
	}

	// Pure $ref schema: emit a plain alias to the referenced type. Without
	// this branch the schema falls through every other check (it has empty
	// Type, no Enum, no Properties, no AllOf) and produces no output at all,
	// leaving any downstream reference to this name unresolved at `go build`.
	if s.Ref != "" {
		emitDoc()
		p.linef("type %s = %s", goName, toGoName(spec.RefName(s.Ref)))
		p.line("")
		return p.err
	}

	effective := effectiveSchema(s, api)

	// JSON Schema allows an empty enum array as "no value is valid".
	// Generating code that always rejects everything is rarely the spec
	// author's intent — flag this up front so they can fix the spec.
	if effective.Enum != nil && len(effective.Enum) == 0 {
		return fmt.Errorf("schema %q: empty enum array (no value would be valid); remove the enum or list the allowed values", name)
	}

	// Typed enums: emit a named type, a const block, and a Validate() method.
	// String enums get a Go string type; integer / number / boolean enums get
	// the matching scalar. Each path produces a switch over named constants
	// so the validator and call sites stay symmetric.
	if len(effective.Enum) > 0 && enumScalarKind(effective) != "" {
		kind := enumScalarKind(effective)
		baseType := enumBaseGoType(effective)
		emitDoc()
		p.linef("type %s %s", goName, baseType)
		p.line("")
		p.line("const (")
		seen := make(map[string]string, len(effective.Enum))
		var cases []string
		for _, v := range effective.Enum {
			constSuffix, ok := enumConstSuffix(v, kind)
			if !ok {
				return fmt.Errorf("enum %q: value %v cannot be represented as a Go identifier suffix", name, v)
			}
			constName := goName + constSuffix
			if prev, dup := seen[constName]; dup {
				return fmt.Errorf("enum %q: values %q and %v both produce identifier %q", name, prev, v, constName)
			}
			seen[constName] = fmt.Sprintf("%v", v)
			p.linef("\t%s %s = %s", constName, goName, enumLiteral(v, kind))
			cases = append(cases, constName)
		}
		p.line(")")
		p.line("")
		p.linef("func (v %s) Validate() error {", goName)
		// JSON Schema says enum + other keywords (pattern, min/max) apply
		// in conjunction. Emit the keyword checks first so an out-of-bound
		// value fails its real constraint, then the enum membership check.
		if kind == "string" && s.Pattern != "" {
			varName := "pattern" + goName + "Self"
			p.linef("\tif !%s.MatchString(string(v)) {", varName)
			p.linef("\t\treturn fmt.Errorf(\"invalid %s value: %%q (does not match required pattern)\", string(v))", goName)
			p.line("\t}")
		}
		p.line("\tswitch v {")
		p.linef("\tcase %s:", strings.Join(cases, ", "))
		p.line("\t\treturn nil")
		p.line("\t}")
		// Surface the offending value with a verb that matches the underlying
		// kind — %q reads cleanly for strings; %v stays correct for the rest.
		errVerb := "%v"
		if kind == "string" {
			errVerb = "%q"
		}
		p.linef("\treturn fmt.Errorf(\"invalid %s value: %s\", %s)", goName, errVerb, enumValueExpr(kind))
		p.line("}")
		p.line("")
		return p.err
	}

	// Map-like object: no Properties, no allOf, only additionalProperties.
	// Emitting an empty struct would silently drop every JSON entry the
	// caller sends — schemaToGoType already maps this shape to map[string]X
	// when used as a field type, so we mirror that at the top level with a
	// named alias.
	if effective.Type.Primary() == "object" &&
		len(effective.Properties) == 0 &&
		len(effective.AllOf) == 0 &&
		effective.AdditionalSchema() != nil {
		emitDoc()
		p.linef("type %s = map[string]%s", goName, schemaToGoType(effective.AdditionalSchema(), false))
		p.line("")
		return p.err
	}

	// Object (or allOf) → struct
	if effective.Type.Primary() == "object" || len(effective.Properties) > 0 || len(effective.AllOf) > 0 {
		writeStruct(p, goName, effective, api)
		return p.err
	}

	// Simple primitive alias (e.g. type ID = int64). If the spec declares
	// keyword constraints on the alias (pattern, minLength, minimum, …),
	// emit a NAMED type (not an `=` alias) with a Validate() method so
	// anything that references the type through $ref gets the constraints
	// enforced — otherwise the constraints would silently disappear at
	// every consumer site.
	if !effective.Type.IsEmpty() {
		if hasPrimitiveConstraints(effective) {
			baseType := schemaToGoType(effective, false)
			emitDoc()
			p.linef("type %s %s", goName, baseType)
			p.line("")
			writePrimitiveValidate(p, goName, effective)
			return p.err
		}
		goType := schemaToGoType(effective, false)
		emitDoc()
		p.linef("type %s = %s", goName, goType)
		p.line("")
	}

	return p.err
}

// collectPrimitiveValidateImports adds the imports a primitive-alias
// Validate body needs: utf8 for min/maxLength, regexp for pattern, fmt for
// every error message, math for math.Mod and NaN/Inf bound literals.
func collectPrimitiveValidateImports(s *spec.Schema, imports *importSet) {
	imports.add("fmt")
	switch s.Type.Primary() {
	case "string":
		if s.MinLength != nil || s.MaxLength != nil {
			imports.add("unicode/utf8")
		}
		if s.Pattern != "" {
			imports.add("regexp")
		}
	case "integer", "number":
		if s.MultipleOf != nil {
			imports.add("math")
		}
		if s.Minimum != nil && boundNeedsMath(*s.Minimum) {
			imports.add("math")
		}
		if s.Maximum != nil && boundNeedsMath(*s.Maximum) {
			imports.add("math")
		}
		if v, ok := exclusiveBoundValue(s.ExclusiveMinimum, s.Minimum); ok && boundNeedsMath(v) {
			imports.add("math")
		}
		if v, ok := exclusiveBoundValue(s.ExclusiveMaximum, s.Maximum); ok && boundNeedsMath(v) {
			imports.add("math")
		}
	}
}

// hasPrimitiveConstraints reports whether a primitive (string/integer/
// number/boolean) schema declares any keyword constraint that warrants
// emitting a Validate method on its named type.
func hasPrimitiveConstraints(s *spec.Schema) bool {
	switch s.Type.Primary() {
	case "string":
		return s.MinLength != nil || s.MaxLength != nil || s.Pattern != ""
	case "integer", "number":
		return s.Minimum != nil || s.Maximum != nil ||
			exclusiveBoundActive(s.ExclusiveMinimum) || exclusiveBoundActive(s.ExclusiveMaximum) ||
			s.MultipleOf != nil
	}
	return false
}

// writePrimitiveValidate emits a Validate() method on a named primitive
// type. The method mirrors writeConstraintChecks but operates on the
// receiver `v` directly (no struct field) and uses a per-type pattern var
// distinct from any property-level pattern var.
func writePrimitiveValidate(p *printer, goName string, s *spec.Schema) {
	p.linef("func (v %s) Validate() error {", goName)
	primary := s.Type.Primary()
	switch primary {
	case "string":
		access := fmt.Sprintf("string(v)")
		if s.MinLength != nil {
			p.linef("\tif l := utf8.RuneCountInString(%s); l < %d {", access, *s.MinLength)
			p.linef("\t\treturn fmt.Errorf(\"%s value must be at least %d characters, got %%d\", l)", goName, *s.MinLength)
			p.line("\t}")
		}
		if s.MaxLength != nil {
			p.linef("\tif l := utf8.RuneCountInString(%s); l > %d {", access, *s.MaxLength)
			p.linef("\t\treturn fmt.Errorf(\"%s value must be at most %d characters, got %%d\", l)", goName, *s.MaxLength)
			p.line("\t}")
		}
		if s.Pattern != "" {
			varName := "pattern" + goName + "Self"
			p.linef("\tif !%s.MatchString(%s) {", varName, access)
			p.linef("\t\treturn fmt.Errorf(\"%s value does not match required pattern\")", goName)
			p.line("\t}")
		}
	case "integer", "number":
		access := fmt.Sprintf("%s(v)", schemaToGoType(s, false))
		switch {
		case exclusiveBoundActive(s.ExclusiveMinimum):
			if val, ok := exclusiveBoundValue(s.ExclusiveMinimum, s.Minimum); ok {
				lit := formatBound(val, primary)
				p.linef("\tif !(%s > %s) {", access, lit)
				p.linef("\t\treturn fmt.Errorf(\"%s value must be > %s, got %%v\", %s)", goName, lit, access)
				p.line("\t}")
			}
		case s.Minimum != nil:
			lit := formatBound(*s.Minimum, primary)
			p.linef("\tif %s < %s {", access, lit)
			p.linef("\t\treturn fmt.Errorf(\"%s value must be >= %s, got %%v\", %s)", goName, lit, access)
			p.line("\t}")
		}
		switch {
		case exclusiveBoundActive(s.ExclusiveMaximum):
			if val, ok := exclusiveBoundValue(s.ExclusiveMaximum, s.Maximum); ok {
				lit := formatBound(val, primary)
				p.linef("\tif !(%s < %s) {", access, lit)
				p.linef("\t\treturn fmt.Errorf(\"%s value must be < %s, got %%v\", %s)", goName, lit, access)
				p.line("\t}")
			}
		case s.Maximum != nil:
			lit := formatBound(*s.Maximum, primary)
			p.linef("\tif %s > %s {", access, lit)
			p.linef("\t\treturn fmt.Errorf(\"%s value must be <= %s, got %%v\", %s)", goName, lit, access)
			p.line("\t}")
		}
		if s.MultipleOf != nil {
			lit := formatBound(*s.MultipleOf, primary)
			p.linef("\tif math.Mod(float64(%s), float64(%s)) != 0 {", access, lit)
			p.linef("\t\treturn fmt.Errorf(\"%s value must be a multiple of %s, got %%v\", %s)", goName, lit, access)
			p.line("\t}")
		}
	}
	p.line("\treturn nil")
	p.line("}")
	p.line("")
}

// enumScalarKind classifies an enum schema for codegen. Returns one of
// "string", "int", "int32", "int64", "float32", "float64", "bool" — or ""
// when the schema's type is something we don't currently emit a named enum
// for (object/array/etc.).
func enumScalarKind(s *spec.Schema) string {
	switch s.Type.Primary() {
	case "string", "":
		return "string"
	case "integer":
		switch s.Format {
		case "int32":
			return "int32"
		case "int64":
			return "int64"
		default:
			return "int"
		}
	case "number":
		if s.Format == "float" {
			return "float32"
		}
		return "float64"
	case "boolean":
		return "bool"
	}
	return ""
}

// enumBaseGoType returns the Go base type for "type X kind" declarations.
func enumBaseGoType(s *spec.Schema) string {
	return enumScalarKind(s)
}

// enumConstSuffix derives the PascalCase suffix appended to the enum type
// name for each constant. Strings become toGoName(value); numerics become
// the digits, with a leading "Neg" for negatives and decimals rewritten so
// the result is a legal Go identifier; booleans become True / False.
//
// NaN / ±Inf as enum entries are rejected (ok=false): Go's `const` block
// only accepts constant expressions, and math.NaN() / math.Inf() aren't
// constants. The values are also non-representable in JSON itself, so the
// rejection mirrors what wire-level serialisers would do.
func enumConstSuffix(v any, kind string) (string, bool) {
	switch kind {
	case "string":
		return toGoName(fmt.Sprintf("%v", v)), true
	case "bool":
		if b, ok := v.(bool); ok {
			if b {
				return "True", true
			}
			return "False", true
		}
		return "", false
	case "int", "int32", "int64":
		switch n := v.(type) {
		case int:
			if !numericIsFinite(float64(n)) {
				return "", false
			}
			return numericSuffix(float64(n), true), true
		case int64:
			return numericSuffix(float64(n), true), true
		case float64:
			if !numericIsFinite(n) {
				return "", false
			}
			return numericSuffix(n, true), true
		case uint64:
			return numericSuffix(float64(n), true), true
		}
		return "", false
	case "float32", "float64":
		switch n := v.(type) {
		case float64:
			if !numericIsFinite(n) {
				return "", false
			}
			return numericSuffix(n, false), true
		case int:
			return numericSuffix(float64(n), false), true
		case int64:
			return numericSuffix(float64(n), false), true
		}
		return "", false
	}
	return "", false
}

// numericIsFinite reports whether v can appear in a Go `const` initialiser.
// NaN / ±Inf must use a runtime expression (math.NaN() / math.Inf()) which
// the const block rejects.
func numericIsFinite(v float64) bool {
	return !math.IsNaN(v) && !math.IsInf(v, 0)
}

// numericSuffix renders a JSON number as a Go-identifier-safe fragment for
// use in enum constant names. The integer flag turns off the decimal-point
// branch so int enum constants don't carry a ".0".
func numericSuffix(n float64, asInt bool) string {
	if math.IsNaN(n) {
		return "NaN"
	}
	if math.IsInf(n, 1) {
		return "PosInf"
	}
	if math.IsInf(n, -1) {
		return "NegInf"
	}
	if asInt {
		i := int64(n)
		if i < 0 {
			return "Neg" + fmt.Sprintf("%d", -i)
		}
		return fmt.Sprintf("%d", i)
	}
	s := fmt.Sprintf("%g", n)
	s = strings.ReplaceAll(s, "+", "")
	s = strings.ReplaceAll(s, "-", "Neg")
	s = strings.ReplaceAll(s, ".", "_")
	return s
}

// enumLiteral renders the Go literal form of an enum value for the const
// block. Strings are %q'd, booleans become true/false, numerics use a kind-
// matched literal.
func enumLiteral(v any, kind string) string {
	switch kind {
	case "string":
		return fmt.Sprintf("%q", fmt.Sprintf("%v", v))
	case "bool":
		if b, ok := v.(bool); ok && b {
			return "true"
		}
		return "false"
	case "int", "int32", "int64":
		switch n := v.(type) {
		case int:
			return fmt.Sprintf("%d", n)
		case int64:
			return fmt.Sprintf("%d", n)
		case float64:
			return fmt.Sprintf("%d", int64(n))
		case uint64:
			return fmt.Sprintf("%d", n)
		}
	case "float32", "float64":
		switch n := v.(type) {
		case float64:
			return formatBound(n, "number")
		case int:
			return formatBound(float64(n), "number")
		case int64:
			return formatBound(float64(n), "number")
		}
	}
	return fmt.Sprintf("%v", v)
}

// enumValueExpr returns the format-arg expression used inside the
// "invalid %s value: …" error. String enums need a string conversion so %q
// quotes them; the rest print fine via %v.
func enumValueExpr(kind string) string {
	if kind == "string" {
		return "string(v)"
	}
	return "v"
}

// resolveToConcrete follows a ref chain until it lands on a schema with a
// non-ref body (or a dead end). Returns nil for malformed refs. Cycle-safe
// via a visited set keyed by the ref string.
func resolveToConcrete(s *spec.Schema, api *spec.OpenAPI) *spec.Schema {
	visited := map[string]bool{}
	cur := s
	for cur != nil && cur.Ref != "" {
		if visited[cur.Ref] {
			return nil
		}
		visited[cur.Ref] = true
		r, _, err := spec.ResolveSchema(cur.Ref, api)
		if err != nil || r == nil {
			return nil
		}
		cur = r
	}
	return cur
}

func writeStruct(p *printer, goName string, s *spec.Schema, api *spec.OpenAPI) {
	// Go through effectiveSchema so allOf branches AND parent-level
	// properties/required both contribute — JSON Schema treats them as an
	// intersection, not "one or the other".
	effective := effectiveSchema(s, api)

	if s.Description != "" {
		p.linef("// %s %s", goName, sanitizeComment(s.Description))
	}
	p.linef("type %s struct {", goName)

	requiredSet := make(map[string]bool, len(effective.Required))
	for _, r := range effective.Required {
		requiredSet[r] = true
	}

	for _, fieldName := range sortedKeys(effective.Properties) {
		fieldSchema := effective.Properties[fieldName]
		goField := toGoFieldName(fieldName)
		required := requiredSet[fieldName]
		goType := schemaToGoType(fieldSchema, !required)

		jsonTag := fieldName
		if !required {
			jsonTag += ",omitempty"
		}

		if fieldSchema.Description != "" {
			p.linef("\t// %s", sanitizeComment(fieldSchema.Description))
		}
		p.linef("\t%s %s `json:\"%s\"`", goField, goType, jsonTag)
	}
	p.line("}")
	p.line("")

	// Generate Validate() method if there are required fields, enum fields, or
	// any validation keyword on a property.
	if hasValidation(effective, api) {
		writeStructValidate(p, goName, effective, api)
	}
}

func writeStructValidate(p *printer, goName string, s *spec.Schema, api *spec.OpenAPI) {
	requiredSet := make(map[string]bool, len(s.Required))
	for _, r := range s.Required {
		requiredSet[r] = true
	}

	p.linef("func (v %s) Validate() error {", goName)

	for _, fieldName := range sortedKeys(s.Properties) {
		fieldSchema := s.Properties[fieldName]
		goField := toGoFieldName(fieldName)
		required := requiredSet[fieldName]
		writeFieldValidate(p, goName, goField, fieldName, fieldSchema, required, api)
	}

	p.line("\treturn nil")
	p.line("}")
	p.line("")
}

// writeFieldValidate emits the validation block for one struct field.
// Required fields are checked directly; optional (pointer) fields are checked
// only when non-nil, with the dereference happening once per block.
func writeFieldValidate(p *printer, goStruct, goField, jsonName string, schema *spec.Schema, required bool, api *spec.OpenAPI) {
	goType := schemaToGoType(schema, false)
	resolved := schema
	if schema.Ref != "" {
		if r, _, err := spec.ResolveSchema(schema.Ref, api); err == nil {
			resolved = r
		}
	}

	// Required: zero/nil rejection. We detect the underlying Go kind to
	// catch ref'd primitive aliases too — `type Name = string` makes a
	// field declared as `Name` substitutable for `string`, so the same
	// `== ""` zero check applies. Without the resolution, a required
	// field of a refd plain-string type silently lost its zero check.
	if required {
		gt := goType
		if schema.Ref != "" {
			if r := resolveToConcrete(schema, api); r != nil {
				rt := schemaToGoType(r, false)
				// Only override when the resolved type is a primitive
				// kind we know how to zero-check; otherwise keep gt as
				// the original ref name and fall through to the nested-
				// struct branches below.
				switch rt {
				case "string":
					gt = "string"
				}
			}
		}
		switch {
		case gt == "string":
			p.linef("\tif v.%s == \"\" {", goField)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' is required\")", jsonName)
			p.line("\t}")
		case strings.HasPrefix(goType, "[]") || strings.HasPrefix(goType, "map["):
			p.linef("\tif v.%s == nil {", goField)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' is required\")", jsonName)
			p.line("\t}")
		}
	}

	// Enum delegation and nested-struct delegation are split rather than merged
	// because they're mutually exclusive (a schema is either an enum or a
	// struct, not both) and the split keeps `hasValidation` parity readable —
	// the enum branch fires whenever the referenced schema has Enum entries,
	// regardless of whether it would also pass hasValidation.
	if schema.Ref != "" && len(resolved.Enum) > 0 {
		if required {
			p.linef("\tif err := v.%s.Validate(); err != nil {", goField)
			p.linef("\t\treturn fmt.Errorf(\"field '%s': %%w\", err)", jsonName)
			p.line("\t}")
		} else {
			p.linef("\tif v.%s != nil {", goField)
			p.linef("\t\tif err := v.%s.Validate(); err != nil {", goField)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s': %%w\", err)", jsonName)
			p.line("\t\t}")
			p.line("\t}")
		}
	}

	// Nested struct validation: if the referenced schema generates its own
	// Validate (because it has required fields or validation keywords).
	if schema.Ref != "" && len(resolved.Enum) == 0 && hasValidation(effectiveSchema(resolved, api), api) {
		if required {
			p.linef("\tif err := v.%s.Validate(); err != nil {", goField)
			p.linef("\t\treturn fmt.Errorf(\"field '%s': %%w\", err)", jsonName)
			p.line("\t}")
		} else {
			// Optional ref fields are pointers; nil → skip, else deref+validate.
			p.linef("\tif v.%s != nil {", goField)
			p.linef("\t\tif err := v.%s.Validate(); err != nil {", goField)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s': %%w\", err)", jsonName)
			p.line("\t\t}")
			p.line("\t}")
		}
	}

	// Inline enum (no $ref) on string / integer / number / boolean fields:
	// emit an in-place switch on the field value. Without this branch the
	// spec's enum constraint would silently disappear — JSON would just
	// pass through any value of the underlying type.
	if schema.Ref == "" && len(schema.Enum) > 0 && enumScalarKind(schema) != "" {
		writeInlineEnumCheck(p, goField, jsonName, schema, required)
	}

	// Keyword constraints: minLength/maxLength/pattern (strings), minimum/maximum
	// (numbers), minItems/maxItems (arrays). Only applied on the field's own schema.
	writeConstraintChecks(p, goStruct, goField, jsonName, schema, required)
}

// writeInlineEnumCheck emits a switch over the field value comparing it
// against the spec's enum entries. Optional (pointer) fields are guarded by
// a nil check and dereferenced; required fields are checked directly. The
// branch covers string, integer, number, and boolean enums — the kind is
// derived from the schema so the case literals and error verb match.
func writeInlineEnumCheck(p *printer, goField, jsonName string, schema *spec.Schema, required bool) {
	kind := enumScalarKind(schema)
	caseLiterals := make([]string, 0, len(schema.Enum))
	displayParts := make([]string, 0, len(schema.Enum))
	for _, v := range schema.Enum {
		caseLiterals = append(caseLiterals, enumLiteral(v, kind))
		displayParts = append(displayParts, fmt.Sprintf("%v", v))
	}
	access := "v." + goField
	indent := "\t"
	if !required {
		p.linef("\tif v.%s != nil {", goField)
		access = "*v." + goField
		indent = "\t\t"
	}
	p.linef(indent+"switch %s {", access)
	p.linef(indent+"case %s:", strings.Join(caseLiterals, ", "))
	p.line(indent + "default:")
	// %q reads cleanly for strings ("\"x\""); other types fall back to %v.
	errVerb := "%v"
	if kind == "string" {
		errVerb = "%q"
	}
	p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be one of [%s], got %s\", %s)",
		jsonName, strings.Join(displayParts, ", "), errVerb, access)
	p.line(indent + "}")
	if !required {
		p.line("\t}")
	}
}

// writeConstraintChecks emits validation for schema-level keywords other than
// "required" and "enum". For optional scalar fields it dereferences the
// pointer; for required scalars it uses the value directly.
func writeConstraintChecks(p *printer, goStruct, goField, jsonName string, schema *spec.Schema, required bool) {
	primary := schema.Type.Primary()
	hasStringChecks := primary == "string" && (schema.MinLength != nil || schema.MaxLength != nil || schema.Pattern != "")
	hasNumberRangeChecks := (primary == "integer" || primary == "number") &&
		(schema.Minimum != nil || schema.Maximum != nil ||
			exclusiveBoundActive(schema.ExclusiveMinimum) || exclusiveBoundActive(schema.ExclusiveMaximum))
	hasMultipleOf := (primary == "integer" || primary == "number") && schema.MultipleOf != nil
	hasNumberChecks := hasNumberRangeChecks || hasMultipleOf
	hasArrayLenChecks := primary == "array" && (schema.MinItems != nil || schema.MaxItems != nil)
	hasArrayUniqueCheck := primary == "array" && schema.UniqueItems
	hasArrayItemChecks := primary == "array" && schema.Items != nil && hasItemKeywordConstraint(schema.Items)
	hasArrayChecks := hasArrayLenChecks || hasArrayUniqueCheck || hasArrayItemChecks
	isMapLike := primary == "object" || (schema.Type.IsEmpty() && schema.AdditionalSchema() != nil)
	hasMapSizeChecks := isMapLike && (schema.MinProperties != nil || schema.MaxProperties != nil)
	if !hasStringChecks && !hasNumberChecks && !hasArrayChecks && !hasMapSizeChecks {
		return
	}

	access := "v." + goField
	if !required && (primary == "string" || primary == "integer" || primary == "number") {
		// Optional scalars are pointers; guard and dereference.
		p.linef("\tif v.%s != nil {", goField)
		access = "(*v." + goField + ")"
	}
	indent := "\t"
	if !required && (primary == "string" || primary == "integer" || primary == "number") {
		indent = "\t\t"
	}

	switch primary {
	case "string":
		if schema.MinLength != nil {
			p.linef(indent+"if l := utf8.RuneCountInString(%s); l < %d {", access, *schema.MinLength)
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be at least %d characters, got %%d\", l)", jsonName, *schema.MinLength)
			p.line(indent + "}")
		}
		if schema.MaxLength != nil {
			p.linef(indent+"if l := utf8.RuneCountInString(%s); l > %d {", access, *schema.MaxLength)
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be at most %d characters, got %%d\", l)", jsonName, *schema.MaxLength)
			p.line(indent + "}")
		}
		if schema.Pattern != "" {
			varName := patternVarName(goStruct, goField)
			p.linef(indent+"if !%s.MatchString(%s) {", varName, access)
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' does not match required pattern\")", jsonName)
			p.line(indent + "}")
		}
	case "integer", "number":
		// exclusiveMinimum/Maximum eats minimum/maximum when both forms set
		// the same boundary — emitting both would double-fail with confusing
		// messages. 3.0 spec authors use `minimum: X` + `exclusiveMinimum: true`
		// (paired), 3.1 spec authors use `exclusiveMinimum: X` alone.
		// We prefer the strict form when active.
		switch {
		case exclusiveBoundActive(schema.ExclusiveMinimum):
			if v, ok := exclusiveBoundValue(schema.ExclusiveMinimum, schema.Minimum); ok {
				lit := formatBound(v, primary)
				p.linef(indent+"if !(%s > %s) {", access, lit)
				p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be > %s, got %%v\", %s)", jsonName, lit, access)
				p.line(indent + "}")
			}
		case schema.Minimum != nil:
			p.linef(indent+"if %s < %s {", access, formatBound(*schema.Minimum, primary))
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be >= %s, got %%v\", %s)", jsonName, formatBound(*schema.Minimum, primary), access)
			p.line(indent + "}")
		}
		switch {
		case exclusiveBoundActive(schema.ExclusiveMaximum):
			if v, ok := exclusiveBoundValue(schema.ExclusiveMaximum, schema.Maximum); ok {
				lit := formatBound(v, primary)
				p.linef(indent+"if !(%s < %s) {", access, lit)
				p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be < %s, got %%v\", %s)", jsonName, lit, access)
				p.line(indent + "}")
			}
		case schema.Maximum != nil:
			p.linef(indent+"if %s > %s {", access, formatBound(*schema.Maximum, primary))
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be <= %s, got %%v\", %s)", jsonName, formatBound(*schema.Maximum, primary), access)
			p.line(indent + "}")
		}
		if schema.MultipleOf != nil {
			// multipleOf via math.Mod handles both ints and floats. The exact
			// equality is fine for integers; for floats the spec accepts
			// implementation-defined precision, so we keep the literal check.
			lit := formatBound(*schema.MultipleOf, primary)
			p.linef(indent+"if math.Mod(float64(%s), float64(%s)) != 0 {", access, lit)
			p.linef(indent+"\treturn fmt.Errorf(\"field '%s' must be a multiple of %s, got %%v\", %s)", jsonName, lit, access)
			p.line(indent + "}")
		}
	case "array":
		// Arrays: required is irrelevant (nil-check above covers it). len() works
		// on nil slices too — returns 0, so the constraints naturally catch
		// "field present but too short".
		if schema.MinItems != nil {
			p.linef("\tif l := len(v.%s); l < %d {", goField, *schema.MinItems)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' must have at least %d items, got %%d\", l)", jsonName, *schema.MinItems)
			p.line("\t}")
		}
		if schema.MaxItems != nil {
			p.linef("\tif l := len(v.%s); l > %d {", goField, *schema.MaxItems)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' must have at most %d items, got %%d\", l)", jsonName, *schema.MaxItems)
			p.line("\t}")
		}
		// Per-item validation: emit a loop only when the items schema declares
		// keywords we know how to check. The element variable is named
		// item; index i is included in the error so callers can locate the
		// offending entry.
		if hasArrayItemChecks {
			writeItemChecks(p, goStruct, goField, jsonName, schema.Items)
		}
		if schema.UniqueItems {
			// O(n²) for arbitrary types; fine for short JSON arrays in
			// validation context. We compare via Go == so the element type
			// must be comparable. Non-comparable element types (slices of
			// slices, structs containing slices) panic at runtime — yaggo
			// can't statically check that here, document as caveat.
			p.linef("\t{")
			p.linef("\t\tseen := make(map[any]struct{}, len(v.%s))", goField)
			p.linef("\t\tfor _, item := range v.%s {", goField)
			p.linef("\t\t\tif _, dup := seen[item]; dup {")
			p.linef("\t\t\t\treturn fmt.Errorf(\"field '%s' must have unique items\")", jsonName)
			p.linef("\t\t\t}")
			p.linef("\t\t\tseen[item] = struct{}{}")
			p.linef("\t\t}")
			p.linef("\t}")
		}
	}

	if isMapLike {
		if schema.MinProperties != nil {
			p.linef("\tif l := len(v.%s); l < %d {", goField, *schema.MinProperties)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' must have at least %d entries, got %%d\", l)", jsonName, *schema.MinProperties)
			p.line("\t}")
		}
		if schema.MaxProperties != nil {
			p.linef("\tif l := len(v.%s); l > %d {", goField, *schema.MaxProperties)
			p.linef("\t\treturn fmt.Errorf(\"field '%s' must have at most %d entries, got %%d\", l)", jsonName, *schema.MaxProperties)
			p.line("\t}")
		}
	}

	if !required && (primary == "string" || primary == "integer" || primary == "number") {
		p.line("\t}")
	}
}

// writeItemChecks emits a per-element loop validating an array field's items
// against its `items.*` keyword constraints (pattern / min{Length,imum} /
// max{Length,imum}). Item-level refs and nested arrays are NOT followed
// here — those are reached when the referenced schema generates its own
// Validate, or are simply unsupported (nested array of array).
func writeItemChecks(p *printer, goStruct, goField, jsonName string, items *spec.Schema) {
	p.linef("\tfor i, item := range v.%s {", goField)
	switch items.Type.Primary() {
	case "string":
		if items.MinLength != nil {
			p.linef("\t\tif l := utf8.RuneCountInString(item); l < %d {", *items.MinLength)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be at least %d characters, got %%d\", i, l)", jsonName, *items.MinLength)
			p.line("\t\t}")
		}
		if items.MaxLength != nil {
			p.linef("\t\tif l := utf8.RuneCountInString(item); l > %d {", *items.MaxLength)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be at most %d characters, got %%d\", i, l)", jsonName, *items.MaxLength)
			p.line("\t\t}")
		}
		if items.Pattern != "" {
			varName := itemPatternVarName(goStruct, goField)
			p.linef("\t\tif !%s.MatchString(item) {", varName)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] does not match required pattern\", i)", jsonName)
			p.line("\t\t}")
		}
	case "integer", "number":
		typ := items.Type.Primary()
		switch {
		case exclusiveBoundActive(items.ExclusiveMinimum):
			if v, ok := exclusiveBoundValue(items.ExclusiveMinimum, items.Minimum); ok {
				lit := formatBound(v, typ)
				p.linef("\t\tif !(item > %s) {", lit)
				p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be > %s, got %%v\", i, item)", jsonName, lit)
				p.line("\t\t}")
			}
		case items.Minimum != nil:
			lit := formatBound(*items.Minimum, typ)
			p.linef("\t\tif item < %s {", lit)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be >= %s, got %%v\", i, item)", jsonName, lit)
			p.line("\t\t}")
		}
		switch {
		case exclusiveBoundActive(items.ExclusiveMaximum):
			if v, ok := exclusiveBoundValue(items.ExclusiveMaximum, items.Maximum); ok {
				lit := formatBound(v, typ)
				p.linef("\t\tif !(item < %s) {", lit)
				p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be < %s, got %%v\", i, item)", jsonName, lit)
				p.line("\t\t}")
			}
		case items.Maximum != nil:
			lit := formatBound(*items.Maximum, typ)
			p.linef("\t\tif item > %s {", lit)
			p.linef("\t\t\treturn fmt.Errorf(\"field '%s'[%%d] must be <= %s, got %%v\", i, item)", jsonName, lit)
			p.line("\t\t}")
		}
	}
	p.line("\t}")
}

// formatBound renders a JSON-Schema numeric bound as a Go expression.
// Integer schemas get an integer literal (no ".0"), number schemas get a
// float literal. NaN / ±Inf — which YAML 1.2 permits as ".nan" / ".inf" —
// can't be expressed as a Go float literal, so we emit math.NaN() /
// math.Inf(±1) instead. Emitting code paths must add the "math" import
// when this fires; collectValidationImports handles that.
func formatBound(v float64, primary string) string {
	if math.IsNaN(v) {
		return "math.NaN()"
	}
	if math.IsInf(v, 1) {
		return "math.Inf(1)"
	}
	if math.IsInf(v, -1) {
		return "math.Inf(-1)"
	}
	if primary == "integer" {
		return fmt.Sprintf("%d", int64(v))
	}
	// Use %g so 1.5 stays 1.5 and 1 becomes "1"; force a decimal point for the
	// integer case so the literal is unambiguously float.
	s := fmt.Sprintf("%g", v)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// boundNeedsMath reports whether formatBound(v, _) would emit a math.*
// helper. Callers use this to decide whether to add the "math" import.
func boundNeedsMath(v float64) bool {
	return math.IsNaN(v) || math.IsInf(v, 0)
}

// exclusiveBoundActive reports whether an exclusiveMinimum/exclusiveMaximum
// keyword should emit a check. Two YAML shapes count as active:
//
//   - 3.1 numeric form: e.b.Value is non-nil (the exclusive boundary itself).
//   - 3.0 boolean form: e.b.Set && e.b.Bool — it pairs with minimum/maximum
//     to convert the inclusive check into a strict one.
//
// The pure "set: true, bool: false" case is treated as a no-op since 3.0
// uses the absence of the keyword to mean "inclusive".
func exclusiveBoundActive(e spec.ExclusiveBound) bool {
	if e.Value != nil {
		return true
	}
	return e.Set && e.Bool
}

// exclusiveBoundValue resolves the comparison value an exclusive bound
// check should use. For the 3.1 numeric form the value is the field itself;
// for the 3.0 boolean form the paired minimum/maximum supplies the value.
// Returns (value, ok=false) when no usable value is available.
func exclusiveBoundValue(e spec.ExclusiveBound, paired *float64) (float64, bool) {
	if e.Value != nil {
		return *e.Value, true
	}
	if e.Set && e.Bool && paired != nil {
		return *paired, true
	}
	return 0, false
}

// patternVarName is the package-level name used for a compiled regex
// matched against the field's own value.
//
// The underscore separator between struct and field parts is load-bearing:
// toGoName / toGoFieldName never emit underscores in their output (they split
// on "_" and join without separator), so "pattern_A_BC" can never equal
// "pattern_AB_C" even though "pattern" + "AB" + "C" == "pattern" + "A" + "BC".
// Without the separator those two schemas would produce duplicate var declarations.
func patternVarName(goStruct, goField string) string {
	return "pattern_" + goStruct + "_" + goField
}

// itemPatternVarName is the package-level name for a compiled regex matched
// against each element of an array-typed field. The "_item" suffix uses an
// underscore for the same collision-prevention reason as patternVarName.
func itemPatternVarName(goStruct, goField string) string {
	return "pattern_" + goStruct + "_" + goField + "_item"
}

// emitPatternVars walks all properties and emits a package-level
// regexp.MustCompile for each schema-level "pattern" we'll match against —
// both field-level (string properties) and item-level (string items inside
// array properties).
func emitPatternVars(p *printer, api *spec.OpenAPI) {
	type entry struct {
		varName string
		pattern string
	}
	var entries []entry
	for _, name := range sortedKeys(api.Components.Schemas) {
		s := api.Components.Schemas[name]
		if s.XGoType != "" {
			continue
		}
		eff := effectiveSchema(s, api)
		goName := toGoName(name)
		// Pattern on the schema itself (named primitive alias with a
		// Validate method) — distinct suffix "Self" so it can coexist with
		// field-level vars on the same struct.
		if eff.Pattern != "" && eff.Type.Primary() == "string" && hasPrimitiveConstraints(eff) {
			entries = append(entries, entry{
				varName: "pattern" + goName + "Self",
				pattern: eff.Pattern,
			})
		}
		for _, fieldName := range sortedKeys(eff.Properties) {
			f := eff.Properties[fieldName]
			if f == nil {
				continue
			}
			if f.Pattern != "" && f.Type.Primary() == "string" {
				entries = append(entries, entry{
					varName: patternVarName(goName, toGoFieldName(fieldName)),
					pattern: f.Pattern,
				})
			}
			if f.Type.Primary() == "array" && f.Items != nil && f.Items.Pattern != "" && f.Items.Type.Primary() == "string" {
				entries = append(entries, entry{
					varName: itemPatternVarName(goName, toGoFieldName(fieldName)),
					pattern: f.Items.Pattern,
				})
			}
		}
	}
	if len(entries) == 0 {
		return
	}
	p.line("var (")
	for _, e := range entries {
		p.linef("\t%s = regexp.MustCompile(%q)", e.varName, e.pattern)
	}
	p.line(")")
	p.line("")
}

// collectValidationImports inspects a top-level schema and adds imports needed
// by the generated Validate() methods (regexp for pattern, unicode/utf8 for
// min/max length). It does NOT recurse into $refs — a referenced schema
// contributes its own imports through its own top-level entry.
func collectValidationImports(s *spec.Schema, imports *importSet) {
	for _, f := range s.Properties {
		if f == nil {
			continue
		}
		if f.Type.Primary() == "string" {
			if f.MinLength != nil || f.MaxLength != nil {
				imports.add("unicode/utf8")
			}
			if f.Pattern != "" {
				imports.add("regexp")
			}
		}
		if (f.Minimum != nil || f.Maximum != nil) && (f.Type.Primary() == "integer" || f.Type.Primary() == "number") {
			imports.add("fmt")
			// NaN / ±Inf bounds expand to math.NaN() / math.Inf() at the
			// callsite, so the consumer package needs the math import.
			if f.Minimum != nil && boundNeedsMath(*f.Minimum) {
				imports.add("math")
			}
			if f.Maximum != nil && boundNeedsMath(*f.Maximum) {
				imports.add("math")
			}
		}
		// exclusiveMinimum / exclusiveMaximum (3.1 numeric form) emits
		// strict-less / strict-greater comparisons and needs fmt+math.
		if (f.Type.Primary() == "integer" || f.Type.Primary() == "number") &&
			(exclusiveBoundActive(f.ExclusiveMinimum) || exclusiveBoundActive(f.ExclusiveMaximum)) {
			imports.add("fmt")
			if v, ok := exclusiveBoundValue(f.ExclusiveMinimum, f.Minimum); ok && boundNeedsMath(v) {
				imports.add("math")
			}
			if v, ok := exclusiveBoundValue(f.ExclusiveMaximum, f.Maximum); ok && boundNeedsMath(v) {
				imports.add("math")
			}
		}
		// multipleOf, minProperties, maxProperties, uniqueItems all use fmt
		// for the rejection message; multipleOf also needs math.Mod.
		if f.MultipleOf != nil && (f.Type.Primary() == "integer" || f.Type.Primary() == "number") {
			imports.add("fmt")
			imports.add("math")
		}
		if f.UniqueItems && f.Type.Primary() == "array" {
			imports.add("fmt")
		}
		if (f.MinProperties != nil || f.MaxProperties != nil) &&
			(f.Type.Primary() == "object" || (f.Type.IsEmpty() && f.AdditionalSchema() != nil)) {
			imports.add("fmt")
		}
		// Inline enum on a property (string/numeric/boolean) emits fmt.Errorf
		// on mismatch.
		if f.Ref == "" && len(f.Enum) > 0 && enumScalarKind(f) != "" {
			imports.add("fmt")
		}
		if f.Type.Primary() == "array" {
			if f.MinItems != nil || f.MaxItems != nil {
				imports.add("fmt")
			}
			// Item-level keyword constraints surface the same imports
			// transitively (utf8 / regexp / fmt). The per-item loop also
			// uses fmt for the indexed error message.
			if f.Items != nil && hasItemKeywordConstraint(f.Items) {
				imports.add("fmt")
				switch f.Items.Type.Primary() {
				case "string":
					if f.Items.MinLength != nil || f.Items.MaxLength != nil {
						imports.add("unicode/utf8")
					}
					if f.Items.Pattern != "" {
						imports.add("regexp")
					}
				case "integer", "number":
					if v, ok := exclusiveBoundValue(f.Items.ExclusiveMinimum, f.Items.Minimum); ok && boundNeedsMath(v) {
						imports.add("math")
					}
					if v, ok := exclusiveBoundValue(f.Items.ExclusiveMaximum, f.Items.Maximum); ok && boundNeedsMath(v) {
						imports.add("math")
					}
					if f.Items.Minimum != nil && boundNeedsMath(*f.Items.Minimum) {
						imports.add("math")
					}
					if f.Items.Maximum != nil && boundNeedsMath(*f.Items.Maximum) {
						imports.add("math")
					}
				}
			}
		}
	}
}

func hasValidation(s *spec.Schema, api *spec.OpenAPI) bool {
	return hasValidationVisited(s, api, map[string]bool{})
}

// hasValidationVisited is the cycle-safe core of hasValidation. visited is
// keyed by the $ref string (not by schema pointer) because two refs can point
// at the same target through different routes; tracking by ref name still
// breaks the loop without false positives. A schema being re-entered is
// reported as "no validation" — the actual validation work will be emitted
// when the recursion's owning schema is generated.
func hasValidationVisited(s *spec.Schema, api *spec.OpenAPI, visited map[string]bool) bool {
	if s == nil {
		return false
	}
	// Top-level $ref: follow the chain so an alias to a constrained
	// primitive / enum / struct propagates its Validate through every
	// hop. Without this, a property referencing `SuperTag` (which is
	// just `$ref: Tag`) never delegates to Tag.Validate().
	if s.Ref != "" {
		if visited[s.Ref] {
			return false
		}
		visited[s.Ref] = true
		resolved, _, err := spec.ResolveSchema(s.Ref, api)
		if err != nil || resolved == nil {
			return false
		}
		return hasValidationVisited(effectiveSchema(resolved, api), api, visited)
	}
	// Top-level enum (string/numeric/boolean) is rendered as a named
	// type with a Validate switch; callers using this schema as a body
	// or field need to delegate to it.
	if len(s.Enum) > 0 && enumScalarKind(s) != "" {
		return true
	}
	// A pure primitive schema (no Properties, no Required) can still
	// carry pattern / min / max / multipleOf — those become a Validate
	// method on the named type. Report true so callers wrap it.
	if hasPrimitiveConstraints(s) {
		return true
	}
	// "required" alone is only meaningful when the field type permits a
	// zero check. For string / slice / map fields the writer emits
	// `== ""` or `== nil`; for numeric/bool we emit nothing (Go's
	// zero value is a legal value, no way to distinguish "missing"
	// without pointers). So treat `required` as triggering Validate
	// only when at least one required field has an enforceable zero check.
	for _, r := range s.Required {
		fs, ok := s.Properties[r]
		if !ok || fs == nil {
			continue
		}
		gt := schemaToGoType(fs, false)
		if gt == "string" || strings.HasPrefix(gt, "[]") || strings.HasPrefix(gt, "map[") {
			return true
		}
		// Required field referencing a primitive string alias (`type X = string`):
		// schemaToGoType returns the alias name, not "string", so the literal
		// check above misses. Resolve the ref chain to detect the underlying
		// string and enable the empty-check emitted by writeFieldValidate.
		if fs.Ref != "" {
			if r := resolveToConcrete(fs, api); r != nil && r.Type.Primary() == "string" {
				return true
			}
		}
	}
	for _, fieldSchema := range s.Properties {
		if fieldSchema == nil {
			continue
		}
		// Keyword constraints on the field itself.
		if hasKeywordConstraint(fieldSchema) {
			return true
		}
		// Inline enum on the property — string/numeric/boolean. The switch-
		// based check is emitted from writeFieldValidate via
		// writeInlineEnumCheck. enumScalarKind decides what we can render.
		if fieldSchema.Ref == "" && len(fieldSchema.Enum) > 0 && enumScalarKind(fieldSchema) != "" {
			return true
		}
		// Enum or transitive validation through a $ref.
		if fieldSchema.Ref != "" {
			if visited[fieldSchema.Ref] {
				continue
			}
			visited[fieldSchema.Ref] = true
			refSchema, _, err := spec.ResolveSchema(fieldSchema.Ref, api)
			if err != nil {
				continue
			}
			if len(refSchema.Enum) > 0 {
				return true
			}
			// Primitive aliases with keyword constraints (pattern, min/max,
			// multipleOf, …) get a named type with a Validate method —
			// that's what we'd call here, so the parent struct needs its
			// own Validate to delegate.
			if hasPrimitiveConstraints(refSchema) {
				return true
			}
			if hasValidationVisited(effectiveSchema(refSchema, api), api, visited) {
				return true
			}
		}
	}
	return false
}

func hasKeywordConstraint(s *spec.Schema) bool {
	if s.Type.Primary() == "string" && (s.MinLength != nil || s.MaxLength != nil || s.Pattern != "") {
		return true
	}
	if s.Type.Primary() == "integer" || s.Type.Primary() == "number" {
		if s.Minimum != nil || s.Maximum != nil {
			return true
		}
		if exclusiveBoundActive(s.ExclusiveMinimum) || exclusiveBoundActive(s.ExclusiveMaximum) {
			return true
		}
		if s.MultipleOf != nil {
			return true
		}
	}
	if s.Type.Primary() == "array" {
		if s.MinItems != nil || s.MaxItems != nil || s.UniqueItems {
			return true
		}
		if s.Items != nil && hasItemKeywordConstraint(s.Items) {
			return true
		}
	}
	// Object / map: minProperties / maxProperties bound the JSON entry count.
	// Detect via Type=="object" OR (empty type with AdditionalProperties),
	// matching schemaToGoType's "this becomes a map" rules.
	if s.Type.Primary() == "object" || (s.Type.IsEmpty() && s.AdditionalSchema() != nil) {
		if s.MinProperties != nil || s.MaxProperties != nil {
			return true
		}
	}
	return false
}

// hasItemKeywordConstraint reports whether an array's items have validation
// keywords we emit Go for. Distinct from hasKeywordConstraint to keep the
// recursion shallow: nested arrays of arrays aren't traversed here, and
// items.$ref validation goes through the ref-walking branch in
// hasValidationVisited rather than this helper.
func hasItemKeywordConstraint(items *spec.Schema) bool {
	if items == nil {
		return false
	}
	switch items.Type.Primary() {
	case "string":
		return items.MinLength != nil || items.MaxLength != nil || items.Pattern != ""
	case "integer", "number":
		return items.Minimum != nil || items.Maximum != nil ||
			exclusiveBoundActive(items.ExclusiveMinimum) || exclusiveBoundActive(items.ExclusiveMaximum)
	}
	return false
}

// effectiveSchema resolves allOf into a flat schema for generation. When the
// parent schema declares both `allOf:` and direct `properties`/`required`,
// JSON Schema semantics require both to apply (the value must satisfy every
// branch and the parent), so we mix the parent's own properties on top of
// the merged allOf result instead of discarding them.
func effectiveSchema(s *spec.Schema, api *spec.OpenAPI) *spec.Schema {
	if len(s.AllOf) == 0 {
		return s
	}
	merged := mergeAllOf(s.AllOf, api)
	if len(s.Properties) > 0 || len(s.Required) > 0 {
		// Don't mutate the input — mergeAllOf returns a freshly allocated
		// schema, but we still want a defensive copy when overlaying parent
		// fields onto it, in case callers re-enter through a different path.
		if merged.Properties == nil {
			merged.Properties = make(map[string]*spec.Schema, len(s.Properties))
		}
		for k, v := range s.Properties {
			merged.Properties[k] = v
		}
		merged.Required = dedupStrings(append(merged.Required, s.Required...))
	}
	return merged
}

// importSet collects distinct import paths and renders them as a Go import block.
type importSet struct {
	paths map[string]struct{}
}

func newImportSet() *importSet { return &importSet{paths: map[string]struct{}{}} }

func (i *importSet) add(p string) {
	if p == "" {
		return
	}
	i.paths[p] = struct{}{}
}

// writeBlock emits a Go import block. Stdlib (no dot in path) is sorted first,
// then a blank line, then external paths sorted. A single-import set uses the
// short form (`import "fmt"`) because gofmt preserves the grouping we emit —
// it won't collapse a single-entry block on our behalf.
func (i *importSet) writeBlock(p *printer) {
	if len(i.paths) == 0 {
		return
	}
	var stdlib, external []string
	for path := range i.paths {
		if strings.Contains(path, ".") {
			external = append(external, path)
		} else {
			stdlib = append(stdlib, path)
		}
	}
	sort.Strings(stdlib)
	sort.Strings(external)
	if len(i.paths) == 1 {
		var only string
		if len(stdlib) == 1 {
			only = stdlib[0]
		} else {
			only = external[0]
		}
		p.linef("import %q", only)
		p.line("")
		return
	}
	p.line("import (")
	for _, s := range stdlib {
		p.linef("\t%q", s)
	}
	if len(stdlib) > 0 && len(external) > 0 {
		p.line("")
	}
	for _, s := range external {
		p.linef("\t%q", s)
	}
	p.line(")")
	p.line("")
}

// printer is a simple line-oriented writer that latches the first error.
type printer struct {
	w   io.Writer
	err error
}

func (p *printer) line(s string) {
	if p.err != nil {
		return
	}
	_, p.err = fmt.Fprintln(p.w, s)
}

func (p *printer) linef(format string, args ...any) {
	if p.err != nil {
		return
	}
	_, p.err = fmt.Fprintf(p.w, format+"\n", args...)
}
